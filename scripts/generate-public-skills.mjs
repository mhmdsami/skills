// Bundles skills/<name>/SKILL.md into a module so the Worker can serve them
// without filesystem access at runtime. Run before build/dev/deploy.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const skillsDir = path.join(process.cwd(), "skills");
const out = path.join(process.cwd(), "src", "lib", "public-skills.generated.ts");

let entries = [];
try {
  entries = await readdir(skillsDir, { withFileTypes: true });
} catch {
  entries = [];
}

const files = {};
for (const entry of entries.filter((item) => item.isDirectory())) {
  try {
    files[entry.name] = await readFile(path.join(skillsDir, entry.name, "SKILL.md"), "utf8");
  } catch {
    // no SKILL.md in this folder; skip
  }
}

const body = `// Generated by scripts/generate-public-skills.mjs. Do not edit.\nexport const publicSkillFiles: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
await writeFile(out, body, "utf8");
console.log(`generated ${Object.keys(files).length} public skill(s) -> src/lib/public-skills.generated.ts`);
